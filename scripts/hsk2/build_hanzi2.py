"""HSK 2: thông tin chữ mới (chưa có ở HSK 1) → src/data/hanziInfo2.ts + nét chữ public/hanzi-data/<chữ>.json.
Hán Việt: bảng HV dưới đây (âm Hán Việt thông dụng, soát tay — Unihan kVietnamese lẫn âm Nôm nên không dùng trực tiếp).
Cấu tạo + mẹo nhớ: scripts/v22/build_mnemonics.py (Make Me a Hanzi decomposition, khuôn câu, không AI).
Nét: node_modules/hanzi-writer-data/<chữ>.json (Make Me a Hanzi). Chạy: python3 scripts/hsk2/build_hanzi2.py"""
import json, re, sys, shutil, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/v22"))
from build_mnemonics import make  # noqa
info = json.loads(re.search(r"HANZI_INFO: Record<string, HanziInfo> = (\{.*?\});\n", (ROOT / "src/data/hanziInfo.ts").read_text()).group(1))
sys.path.insert(0, str(ROOT / "scripts/hsk2"))
from hsk2_src import LESSONS
VN = dict(x.split(" ") for x in "旅 lữ,游 du,踢 thích,足 túc,为 vi,眼 nhãn,睛 tình,运 vận,最 tối,每 mỗi,跑 bào,步 bộ,体 thể,报 báo,纸 chỉ,红 hồng,旁 bàng,表 biểu,送 tống,颜 nhan,色 sắc,丈 trượng,夫 phu,左 tả,粉 phấn,长 trường,介 giới,绍 thiệu,始 thủy,快 khoái,乐 lạc,已 dĩ,经 kinh,帮 bang,就 tựu,咖 ca,啡 phi,考 khảo,试 thí,意 ý,思 tư,鱼 ngư,准 chuẩn,备 bị,错 thác,篮 lam,门 môn,所 sở,羊 dương,肉 nhục,因 nhân,泳 vịnh,自 tự,行 hành,共 cộng,室 thất,离 ly,路 lộ,慢 mạn,远 viễn,走 tẩu,过 quá,等 đẳng,告 cáo,诉 tố,黑 hắc,让 nhượng,情 tình,从 tùng,懂 đổng,跳 khiêu,舞 vũ,完 hoàn,希 hy,望 vọng,迎 nghênh,助 trợ,别 biệt,瓜 qua,洗 tẩy,比 tỷ,姓 tính,右 hữu,近 cận,妻 thê,度 độ,宾 tân,馆 quán,铅 duyên,笔 bút,往 vãng,着 trước,拿 nã,直 trực,但 đãn,晴 tình,虽 tuy,然 nhiên,站 trạm,阴 âm,更 cánh".split(","))
single = {w[0]: w[2] for L in LESSONS for w in L[2] if len(w[0]) == 1}
chars = []
for L in LESSONS:
    for w in L[2] + [(s[0],) for s in L[3]]:
        for c in w[0]:
            if re.match(r"[\u3400-\u9fff]", c) and c not in chars: chars.append(c)
new = [c for c in chars if c not in info]
out, nohv, nostroke = {}, [], []
for c in new:
    hv = VN.get(c, ""); vi = single.get(c, "")
    if not hv: nohv.append(c)
    m = make(c, hv, vi.split(",")[0].lower() if vi else "")
    body = m["text"].split(": ", 1)[1] if ": " in m["text"] else ""
    out[c] = {"hv": hv, "parts": [p[0] for p in m["parts"]], "note": body}
missing = []
for c in chars:
    dst = ROOT / "public/hanzi-data" / f"{c}.json"
    if dst.exists(): continue
    src = ROOT / "node_modules/hanzi-writer-data" / f"{c}.json"
    if src.exists(): shutil.copy(src, dst)
    else: missing.append(c)
(ROOT / "src/data/hanziInfo2.ts").write_text(
    "// AUTO-GENERATED by scripts/hsk2/build_hanzi2.py — chữ mới của HSK 2 (Hán Việt: bảng soát tay; cấu tạo/mẹo: Make Me a Hanzi + khuôn câu).\n"
    "import type { HanziInfo } from \"./hanziInfo\";\nexport const HANZI_INFO2: Record<string, HanziInfo> = " + json.dumps(out, ensure_ascii=False) + ";\n", encoding="utf8")
print("chars", len(chars), "new", len(new), "no hv", nohv, "no stroke data", missing)
for c in new[:8]: print(c, out[c])
