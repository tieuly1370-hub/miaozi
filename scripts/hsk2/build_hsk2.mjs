// Sinh src/data/hsk2.ts từ scripts/hsk2/hsk2_src.py (qua /tmp/hsk2_src.json — chạy: python3 scripts/hsk2/build_hsk2.py)
// Bài HSK 2 đánh số nối tiếp HSK 1: bài 1 của HSK 2 = id 20 (HSK 1 có 19 bài). Từ: n20-01…, câu: s20-01…
import fs from "fs";
import { pinyin } from "pinyin-pro";
const RAW = JSON.parse(fs.readFileSync(process.argv[2] || "/tmp/hsk2_src.json", "utf8"));
const SRC = RAW.lessons, SPY = RAW.py;
const FIRST = 20;
const M = { "ā":"a1","á":"a2","ǎ":"a3","à":"a4","ē":"e1","é":"e2","ě":"e3","è":"e4","ī":"i1","í":"i2","ǐ":"i3","ì":"i4","ō":"o1","ó":"o2","ǒ":"o3","ò":"o4","ū":"u1","ú":"u2","ǔ":"u3","ù":"u4","ǖ":"ü1","ǘ":"ü2","ǚ":"ü3","ǜ":"ü4" };
const strip = (s) => [...s].map((c) => (M[c] ? M[c][0] === "ü" ? "ü" : M[c][0] : c)).join("");
function syl2num(s) { let t = "5", o = ""; for (const c of s) { if (M[c]) { o += M[c].slice(0, -1); t = M[c].slice(-1); } else o += c; } return o.toLowerCase() + t; }
const han = (s) => [...s].filter((c) => /[\u3400-\u9fff]/.test(c));
const bad = [];
function numOf(hz, disp) {
  const cs = han(hz);
  const ref = pinyin(cs.join(""), { toneType: "none", type: "array", v: true }).map((x) => x.replace(/v/g, "ü"));
  const flat = strip(disp.replace(/\s+/g, "")).toLowerCase();
  if (hz === "长") return syl2num(disp);
  if (hz === "玩儿") { /* 玩儿 → wánr */ return syl2num(disp.replace("r", "")) + " r5"; }
  if (ref.join("") !== flat) { bad.push(hz + " " + disp + " vs " + ref.join(" ")); return pinyin(hz, { toneType: "num", v: true }).replace(/0/g, "5"); }
  const d = disp.replace(/\s+/g, ""); let i = 0; const out = [];
  for (const r of ref) { out.push(syl2num(d.slice(i, i + r.length))); i += r.length; }
  return out.join(" ");
}
const lessons = SRC.map(([zh, vi, words, sents], k) => {
  const id = FIRST + k, p2 = String(id).padStart(2, "0");
  return {
    id, titleZh: zh, titleVi: vi, grammarNote: "", level: 2, levelLesson: k + 1,
    words: words.map(([hz, py, v], j) => ({ id: `n${p2}-${String(j + 1).padStart(2, "0")}`, lesson: id, hanzi: hz, pinyin: py, pinyinNum: numOf(hz, py), vi: v, pos: "", decomps: [], mnemonic: "" })),
    sentences: sents.map(([hz, v], j) => {
      const py = SPY[hz];
      const pn = numOf(han(hz).join("").replace(/这儿/g, "这"), py.replace(/[^\p{L}\s]/gu, " ").replace(/Zhèr/i, "zhè").trim()).toLowerCase();
      return { id: `s${p2}-${String(j + 1).padStart(2, "0")}`, lesson: id, hanzi: hz, pinyin: py, pinyinNum: pn, vi: v };
    }),
    lecture: null, workbook: null, days: 3,
  };
});
if (bad.length) console.error("PINYIN MISMATCH:\n" + bad.join("\n"));
fs.writeFileSync("src/data/hsk2.ts", `// AUTO-GENERATED by scripts/hsk2/build_hsk2.mjs — sửa nguồn ở scripts/hsk2/hsk2_src.py rồi chạy lại\nimport type { Lesson } from "./curriculum";\nexport const HSK2_LESSONS: Lesson[] = ${JSON.stringify(lessons, null, 1)};\n`);
console.log("lessons", lessons.length, "words", lessons.reduce((a, l) => a + l.words.length, 0), "sentences", lessons.reduce((a, l) => a + l.sentences.length, 0));

