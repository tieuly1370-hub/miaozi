"""Nhóm nét theo thành phần cấp 1 (Make Me a Hanzi `matches`) cho mọi chữ trong bài học → src/data/compGroups.ts.
Dùng cho chấm viết chặt (src/v2/strictGrade.ts): mỗi thành phần phải đúng vị trí + tỉ lệ. Chạy lại khi thêm cấp HSK mới."""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
MM = {}
for l in (ROOT / "scripts/v22/mmah_dictionary.txt").open(encoding="utf8"):
    j = json.loads(l); MM[j["character"]] = j
chars = set()
for f in ["src/data/curriculum.ts", "src/data/hsk2.ts"]:
    for m in re.finditer(r'"hanzi": "([^"]+)"', (ROOT / f).read_text()):
        chars |= {c for c in m.group(1) if "\u3400" <= c <= "\u9fff"}
out = {}
for c in sorted(chars):
    m = MM.get(c)
    if not m or not m.get("matches"): continue
    g = "".join("x" if not x else str(x[0]) for x in m["matches"])
    if len(set(g) - {"x"}) >= 2: out[c] = g
(ROOT / "src/data/compGroups.ts").write_text("// AUTO-GENERATED by scripts/build_comp_groups.py (Make Me a Hanzi matches) — chữ → nhóm thành phần của từng nét\nexport const COMP_GROUPS: Record<string, string> = " + json.dumps(out, ensure_ascii=False) + ";\n", encoding="utf8")
print(len(chars), "chars,", len(out), "with groups")
