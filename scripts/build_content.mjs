// Sửa pinyin dữ liệu bài + dựng Giáo trình (pinyin, id âm thanh). Chạy: node --experimental-strip-types scripts/build_content.mjs
import fs from "node:fs";
import { LESSONS } from "../src/data/curriculum.ts";
import { setWords, sentencePinyin, setTone, joinSyl } from "./pinyin.mjs";

const NUMFIX = {
  "Zhongguo2": "Zhong1 guo2", "Beijing1": "Bei3 jing1", "shuohua4": "shuo1 hua4", "huochezhan4": "huo3 che1 zhan4",
};
const numToMark = (n) => { const m = n.match(/^([a-zA-Zü]+?)([1-5])$/); if (!m) return n; return setTone(m[1].replace("v", "ü"), Number(m[2])); };
const words = [];
for (const l of LESSONS) for (const w of l.words) {
  if (NUMFIX[w.pinyinNum]) w.pinyinNum = NUMFIX[w.pinyinNum];
  const syl = w.pinyinNum.trim().split(/\s+/).map(numToMark);
  const disp = joinSyl(syl);
  if (disp.toLowerCase() !== w.pinyin.toLowerCase()) console.log("word pinyin", w.hanzi, w.pinyin, "->", disp);
  w.pinyin = disp;
  words.push({ hanzi: w.hanzi, syl: syl.join(" ") });
}
setWords(words);
for (const l of LESSONS) for (const s of l.sentences) {
  const r = sentencePinyin(s.hanzi);
  s.pinyin = r.pinyin; s.pinyinNum = r.pinyinNum;
}
// rewrite curriculum.ts
const path = new URL("../src/data/curriculum.ts", import.meta.url);
const src = fs.readFileSync(path, "utf8");
const start = src.indexOf("export const LESSONS: Lesson[] = ");
const end = src.indexOf("\n];\n", start) + 4;
const next = src.slice(0, start) + "export const LESSONS: Lesson[] = " + JSON.stringify(LESSONS, null, 2) + ";\n" + src.slice(end);
fs.writeFileSync(path, next);

// textbook
const T = JSON.parse(fs.readFileSync(new URL("./textbook-src.json", import.meta.url), "utf8"));
const tts = [];
const line = (id, zh, vi, extra = {}) => { const r = sentencePinyin(zh); tts.push({ id, text: zh, kind: "sent" }); return { id, zh, py: r.pinyin, vi, ...extra }; };
const out = [];
for (const l of LESSONS) {
  const t = T[String(l.id)];
  const id = String(l.id).padStart(2, "0");
  out.push({
    lesson: l.id,
    goals: t.goals,
    grammar: t.grammar.map((g, gi) => ({ title: g.title, pattern: g.pattern, explain: g.explain, ex: g.ex.map(([zh, vi], ei) => line(`g${id}-${gi + 1}-${ei + 1}`, zh, vi)) })),
    dialogues: t.dialogues.map((d, di) => ({ title: d.title, lines: d.lines.map(([who, zh, vi], li) => line(`d${id}-${di + 1}-${li + 1}`, zh, vi, { who })) })),
    notes: t.notes,
  });
}
fs.writeFileSync(new URL("../src/data/textbook.ts", import.meta.url),
  "// AUTO-GENERATED by scripts/build_content.mjs from scripts/textbook_src.py — nội dung tự biên soạn\n" +
  "export type TbLine = { id: string; zh: string; py: string; vi: string; who?: string };\n" +
  "export type TbGrammar = { title: string; pattern: string; explain: string; ex: TbLine[] };\n" +
  "export type TbLesson = { lesson: number; goals: string[]; grammar: TbGrammar[]; dialogues: { title: string; lines: TbLine[] }[]; notes: string[] };\n" +
  "export const TEXTBOOK: TbLesson[] = " + JSON.stringify(out, null, 1) + ";\n");
fs.writeFileSync(new URL("./tts-textbook.json", import.meta.url), JSON.stringify(tts, null, 0));
console.log("textbook lines", tts.length);
